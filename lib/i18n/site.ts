export type UIKey = keyof typeof UI;

export function t(lang: Lang, key: UIKey, vars?: Record<string, string | number>): string {
  const pair = UI[key];
  const out = pair[lang === "en" ? 1 : 0];
  if (!vars) return out;
  return out.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** 路由段 → 语言；[lang] 段之外的旧路径按默认语言处理。 */
export const langOf = (seg: string | undefined): Lang => (isLang(seg) ? seg : DEFAULT_LANG);
/** 另一种语言的同路径，语言切换用。 */
export const otherLang = (lang: Lang): Lang => (lang === "en" ? "zh-CN" : "en");
